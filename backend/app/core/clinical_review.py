def extract_review_status(sheet: str) -> str | None:
    """Return the human-managed section, or None when its markers are absent."""
    if REVIEW_STATUS_BEGIN not in sheet or REVIEW_STATUS_END not in sheet:
        return None
    after_begin = sheet.split(REVIEW_STATUS_BEGIN, 1)[1]
    if REVIEW_STATUS_END not in after_begin:
        return None
    return after_begin.split(REVIEW_STATUS_END, 1)[0].strip()


def generated_review_sections(sheet: str) -> str:
    """Remove the human-managed section for drift comparison."""
    if REVIEW_STATUS_BEGIN not in sheet or REVIEW_STATUS_END not in sheet:
        return sheet
    before, remainder = sheet.split(REVIEW_STATUS_BEGIN, 1)
    _, after = remainder.split(REVIEW_STATUS_END, 1)
    return before + after
