"""A single document listing everything the system tells patients, and the thresholds behind it.

The advice wording and cut-offs are general guidance written by developers, not
clinicians. This renders them all in one place so a clinician can read, correct
and sign them off. `docs/advice-for-clinical-review.md` is generated from it
(`python -m scripts.export_advice`), and a test fails if the file is out of date.
"""

from app.core import factor_insights as fi
from app.core.bp_classification import (
    ELEVATED_DIASTOLIC,
    ELEVATED_SYSTOLIC,
    HIGH_DIASTOLIC,
    HIGH_SYSTOLIC,
    LOW_DIASTOLIC,
    LOW_SYSTOLIC,
)
from app.core.lifestyle_factors import GUIDELINE_MESSAGES

LABELS_LONG = {
    "salt_intake": "Salt",
    "alcohol_consumed": "Alcohol",
    "smoked": "Smoking",
    "physical_activity_minutes": "Physical activity",
    "diet_adherence": "Diet followed",
    "sleep_hours": "Sleep",
    "stress_level": "Stress",
    "caffeine_intake": "Coffee or tea",
    "medication_taken": "Medication",
    "temperature_feel": "Temperature",
    "noise_level": "Noise",
}


def _habit_message(name: str) -> str:
    feature = fi.MODEL_FEATURE.get(name)
    return GUIDELINE_MESSAGES[feature] if feature else fi.RULE_MESSAGES[name]


def render_review_sheet() -> str:
    lines = [
        "# HyperSync: advice and thresholds for clinical review",
        "",
        "_Generated by `python -m scripts.export_advice`; do not edit by hand. To change wording or a cut-off, edit "
        "the code (file names are given below), regenerate, and have this sheet re-signed._",
        "",
        "Everything here is general lifestyle guidance shown to patients. None of it is a diagnosis or a prescription.",
        "",
        "## 1. Blood pressure bands (mmHg)",
        "",
        "Source: `backend/app/core/bp_classification.py` (mirrored in `frontend/src/utils/bpStatus.js`).",
        "",
        "| Band | Rule |",
        "| --- | --- |",
        f"| Low | systolic below {LOW_SYSTOLIC} **or** diastolic below {LOW_DIASTOLIC} |",
        f"| High | systolic {HIGH_SYSTOLIC} or above **or** diastolic {HIGH_DIASTOLIC} or above |",
        f"| Elevated | systolic {ELEVATED_SYSTOLIC} or above **or** diastolic {ELEVATED_DIASTOLIC} or above |",
        "| Controlled | otherwise |",
        "",
        "## 2. Habits patients log, and what is said about them",
        "",
        "Source: `backend/app/core/factor_insights.py`, `lifestyle_factors.py`.",
        "",
    ]
    for name in fi.RISK_PREDICATES:
        lines += [
            f"### {LABELS_LONG[name]}",
            "",
            f"- **Treated as a risk when:** {fi.RISK_TEXT[name]}",
            f"- **Patient is told:** {_habit_message(name)}",
            f"- **Advice to avoid it:** {fi.TIPS[name]}",
            f'- **Used in comparisons as:** "{fi.DESCRIPTIONS[name][0]}" versus "{fi.DESCRIPTIONS[name][1]}"',
            "",
        ]
    lines += [
        "## 3. How each reading was taken",
        "",
        "Patients may record whether they rested for about 5 minutes first, and whether they had coffee/tea, "
        "smoked or exercised in the previous 30 minutes.",
        "",
        f"- Raised when **{fi.MEASUREMENT_MIN_READINGS} or more** readings in the period were taken without rest "
        "or soon after a stimulant.",
        f"- When at least {fi.PATTERN_MIN_DAYS} properly taken readings exist to compare, the gap is shown if it is "
        f"{fi.PATTERN_MIN_DIFF_MMHG} mmHg systolic or more.",
        f"- **Advice:** {fi.MEASUREMENT_TIP}",
        "",
        "## 4. When the system links a habit to the patient's own readings",
        "",
        f"- A habit is raised when risky on the most recent entry, or on **{fi.REPEAT_DAYS}+ days** in the period.",
        f"- A personal pattern needs **{fi.PATTERN_MIN_DAYS}+ days on each side** (risky and not risky) with a "
        f"reading, and an average systolic gap of **{fi.PATTERN_MIN_DIFF_MMHG} mmHg or more**.",
        "- Wording always says it is a link in the patient's own readings, not proof of cause.",
        "- Habits that occurred on exactly the same days are reported together.",
        f"- At most {fi.MAX_PATTERNS} pattern findings are shown. Smoking and missed medication are never the habits "
        "left out for space; anything cut is named.",
        "",
        "## 5. Sign-off",
        "",
        "| Section | Reviewed by | Role | Date | Changes required |",
        "| --- | --- | --- | --- | --- |",
        "| 1. Blood pressure bands | | | | |",
        "| 2. Habit wording and advice | | | | |",
        "| 3. Measurement conditions | | | | |",
        "| 4. Pattern thresholds | | | | |",
        "",
    ]
    return "\n".join(lines)
